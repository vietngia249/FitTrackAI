/**
 * Calculates the interior angle (in degrees) formed by three 2D landmarks (A - B - C)
 * with B as the vertex.
 * Formula: θ = |atan2(Cy - By, Cx - Bx) - atan2(Ay - By, Ax - Bx)| * (180 / π)
 */
export function calculateAngle(
  a: Landmark,
  b: Landmark,
  c: Landmark
): number {
  const radians =
    Math.atan2(c.y - b.y, c.x - b.x) - Math.atan2(a.y - b.y, a.x - b.x);
  let angle = Math.abs((radians * 180.0) / Math.PI);
  if (angle > 180.0) {
    angle = 360.0 - angle;
  }
  return Math.round(angle * 10) / 10;
}

/**
 * Checks whether landmark points have sufficient visibility confidence (default 0.65).
 */
export function areLandmarksVisible(
  landmarks: (Landmark | undefined)[],
  minConfidence = 0.65
): boolean {
  return landmarks.every(
    (lm) => lm && (lm.visibility === undefined || lm.visibility >= minConfidence)
  );
}
